package operators;

/*

Logical Operators -> Used with boolean values.

    Operators
         && Logical AND
         || Logical OR
         ! Logical NOT

 */

public class Logical_OP {
    static void main(String[] args) {

        boolean a = true;
        boolean b = false;

        System.out.println(a && b);
        System.out.println(a || b);
        System.out.println(!a);
    }
}
