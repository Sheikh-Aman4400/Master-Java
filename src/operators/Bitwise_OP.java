package operators;


/*

Bitwise Operators -> Work on binary bits.

    Operators
         &
         |
         ^
         ~

 */
public class Bitwise_OP {
    static void main(String[] args) {

        int a = 5;
        int b = 3;

        System.out.println(a & b);
        System.out.println(a | b);
        System.out.println(a ^ b);
    }
}
