package Operators;

/*

Relational (Comparison) Operators -> Used to compare two values.

    Operators
         == Equal to
         != Not equal to
         > Greater than
         < Less than
         >= Greater than or equal to
         <= Less than or equal to

 */

public class Relational_Comparison_OP {
    static void main(String[] args) {
        int a = 10;
        int b = 20;

        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a < b);
        System.out.println(a > b);
    }
}
