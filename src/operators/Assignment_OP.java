package operators;

/*

Assignment Operators -> Used to assign values to variables.

    Operators
         =
         +=
         -=
         *=
         /=
         %=

 */

public class Assignment_OP {
    static void main(String[] args) {
        int x = 10;

        x += 5;  // x = x + 5
        System.out.println(x);

        x *= 2;  // x = x * 2
        System.out.println(x);
    }
}
